"""
Campus Wellbeing Trend & Referral Dashboard - API entry point.

Run locally with:
    uvicorn main:app --reload --port 8000

This service only ever handles synthetic/demo data in this prototype.
See docs/privacy_and_safety.md for the data-handling principles this
implementation follows.
"""
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from core.config import APP_TITLE, APP_VERSION, ALLOWED_ORIGINS
from api import checkins, dashboard, flags

app = FastAPI(
    title=APP_TITLE,
    version=APP_VERSION,
    description=(
        "Anonymous check-ins, aggregate wellbeing trends, and a conservative "
        "rule-based flag queue that always routes to a human counselor. "
        "No diagnosis or self-harm content is ever generated by this service."
    ),
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(checkins.router)
app.include_router(dashboard.router)
app.include_router(flags.router)


@app.get("/")
def root():
    return {
        "service": APP_TITLE,
        "version": APP_VERSION,
        "status": "ok",
        "note": "Synthetic demo data only. No diagnostic or self-harm content is generated.",
    }


@app.get("/api/health")
def health():
    return {"status": "healthy"}
